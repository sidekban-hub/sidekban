create table if not exists public.sensor (
  id bigint generated by default as identity primary key,
  tinggi_air double precision not null default 0,
  debit_air double precision not null default 0,
  curah_hujan double precision not null default 0,
  status text not null default 'Aman',
  timestamp timestamptz not null default now()
);

-- Untuk tabel sensor yang sudah ada sebelumnya (tidak berpengaruh jika kolom sudah ada)
alter table public.sensor
  add column if not exists curah_hujan double precision not null default 0;

create table if not exists public.riwayat (
  id bigint generated by default as identity primary key,
  tinggi_air double precision not null,
  debit_air double precision not null,
  ts timestamptz not null default now()
);

create table if not exists public.log_status (
  id bigint generated by default as identity primary key,
  status text not null,
  tinggi_air double precision not null default 0,
  debit_air double precision not null default 0,
  ts timestamptz not null default now()
);

-- ===== ROW LEVEL SECURITY =====
alter table public.sensor enable row level security;
alter table public.riwayat enable row level security;
alter table public.log_status enable row level security;

drop policy if exists "Authenticated users can read sensor" on public.sensor;
create policy "Authenticated users can read sensor"
  on public.sensor for select to authenticated using (true);

drop policy if exists "Authenticated users can read riwayat" on public.riwayat;
create policy "Authenticated users can read riwayat"
  on public.riwayat for select to authenticated using (true);

drop policy if exists "Authenticated users can read log_status" on public.log_status;
create policy "Authenticated users can read log_status"
  on public.log_status for select to authenticated using (true);

-- ===== REALTIME =====
-- Menambahkan tabel ke publication hanya jika belum ada (aman dijalankan berulang).
do $$
declare
  nama_tabel text;
begin
  foreach nama_tabel in array array['sensor', 'riwayat', 'log_status']
  loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = nama_tabel
    ) then
      execute format('alter publication supabase_realtime add table public.%I', nama_tabel);
    end if;
  end loop;
end $$;